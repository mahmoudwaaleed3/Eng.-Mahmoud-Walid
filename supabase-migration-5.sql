-- -----------------------------------------------------------------
-- 1) عمود جديد في جدول orders لحفظ رابط صورة الإيصال
-- -----------------------------------------------------------------
alter table orders add column if not exists receipt_url text;

-- بيانات المنتج بقت اختيارية دلوقتي، لأن نموذج "ابعت إيصال" في صفحة
-- التواصل مش بيطلب من الزائر يحدد كورس/كتاب معيّن وقت الرفع
alter table orders alter column product_type drop not null;
alter table orders alter column product_id drop not null;


-- -----------------------------------------------------------------
-- 2) صلاحية جديدة: أي زائر (anon) يقدر "يضيف" طلب بس
--    (زي فورمة رفع الإيصال في صفحة التواصل)
--    من غير ما يقدر يقرا أو يعدّل أو يمسح أي طلب تاني
-- -----------------------------------------------------------------
drop policy if exists "public can submit order" on orders;

create policy "public can submit order" on orders for insert
  to anon
  with check (status = 'pending');


-- -----------------------------------------------------------------
-- 3) Storage bucket لصور إيصالات الدفع
--
-- الأسهل إنك تعمل الخطوة دي من واجهة Supabase مباشرة:
--   Storage → New bucket → الاسم: receipts → فعّل "Public bucket"
--
-- لو حابب تعملها بالكود بدل كده، شغّل السطرين دول (ممكن يحتاجوا
-- صلاحيات أعلى من اللي متاحة في SQL Editor العادي، فلو ظهر معاك
-- error استخدم واجهة Storage بدلها):
-- -----------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('receipts', 'receipts', true)
on conflict (id) do nothing;

-- أي زائر (anon) يقدر يرفع ملف في الـ bucket ده بس (مش يقرا/يمسح ملفات التانية)
drop policy if exists "public can upload receipts" on storage.objects;
create policy "public can upload receipts" on storage.objects for insert
  to anon
  with check (bucket_id = 'receipts');

-- ملحوظة: بما إن الـ bucket "public"، أي حد معاه الرابط المباشر لصورة
-- الإيصال يقدر يشوفها (زي أي صورة عامة على الإنترنت)، بس محدش يقدر
-- يعرف الرابط ده غير من جدول orders في لوحة الأدمن. لو عايز حماية
-- أقوى (يعني السيرفر بس يقدر يوريها)، ده محتاج تحويل الـ bucket
-- لـ private واستخدام "signed URLs" — لو حابب اعمل الخطوة دي قولي.

